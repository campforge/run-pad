#!/usr/bin/env python3
"""Regenerates THIRD-PARTY-NOTICES.txt from what the Invoklet application actually ships.

Lists the third-party source code kept in this repository, every NuGet package (direct and
transitive) of src/main/Invoklet/Invoklet.csproj with its license and copyright, the license texts, and
the notice files that packages and the .NET runtime pack carry for code they embed. Run from the
repository root after changing dependencies, then commit the result:

    dotnet restore
    python scripts/make-third-party-notices.py
"""

from __future__ import annotations

import hashlib
import html
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "src" / "main" / "Invoklet" / "Invoklet.csproj"
LICENSES = Path(__file__).resolve().parent / "third-party"
OUTPUT = ROOT / "THIRD-PARTY-NOTICES.txt"
NUGET = Path(os.environ.get("NUGET_PACKAGES", Path.home() / ".nuget" / "packages"))

# Third-party source code kept (modified) in this repository; license files live next to it.
SOURCE_COMPONENTS = [
    ("AvaloniaEdit and AvaloniaEdit.TextMate",
     "src/controls/AvaloniaEdit, src/controls/AvaloniaEdit.TextMate, tests/AvaloniaEdit.Tests",
     "MIT", "Copyright (c) 2017 Eli Arbel; based on AvalonEdit, "
            "Copyright (c) 2014 AlphaSierraPapa for the SharpDevelop Team",
     "https://github.com/AvaloniaUI/AvaloniaEdit", "src/controls/AvaloniaEdit/LICENSE"),
    ("HTML Renderer", "src/controls/Invoklet.Avalonia.HtmlRenderer/External",
     "BSD-3-Clause", "Copyright (c) 2009 José Manuel Menéndez Poo; "
                     "Copyright (c) 2013-2026 Arthur Teplitzki",
     "https://github.com/ArthurHub/HTML-Renderer",
     "src/controls/Invoklet.Avalonia.HtmlRenderer/External/LICENSE"),
    ("Avalonia.HtmlRenderer", "src/controls/Invoklet.Avalonia.HtmlRenderer",
     "MIT", "Copyright (c) 2014 Steven Kirk",
     "https://github.com/AvaloniaUI/Avalonia.HtmlRenderer",
     "src/controls/Invoklet.Avalonia.HtmlRenderer/LICENSE"),
    ("MarkView.Avalonia and MarkView.Avalonia.SyntaxHighlighting",
     "src/controls/MarkView.Avalonia, src/controls/MarkView.Avalonia.SyntaxHighlighting, "
     "tests/MarkView.Avalonia.Tests, tests/MarkView.Avalonia.SyntaxHighlighting.Tests",
     "MIT", "Copyright (c) 2026 Nicolas Musset",
     "https://github.com/Kryptos-FR/MarkView.Avalonia", "src/controls/MarkView.Avalonia/LICENSE.md"),
    ("Google Material Design Icons — settings (24px)", "src/main/Invoklet/Resources/Icons.axaml",
     "Apache-2.0", "Copyright Google LLC",
     "https://github.com/google/material-design-icons", "scripts/third-party/Apache-2.0.txt"),
]

# Packages that point to a license URL or file instead of an SPDX expression.
LICENSE_OVERRIDES = {
    "System.Data.DataSetExtensions": "MIT",          # licenseUrl: dotnet/corefx LICENSE.TXT (MIT)
    "Avalonia.Angle.Windows.Natives": "BSD-3-Clause",  # LICENSE file: ANGLE Project Authors
}


def packages() -> dict[str, str]:
    out = subprocess.run(["dotnet", "list", str(PROJECT), "package", "--include-transitive",
                          "--format", "json"], capture_output=True, text=True, check=True).stdout
    data = json.loads(out)
    found: dict[str, str] = {}
    for project in data["projects"]:
        for framework in project.get("frameworks", []):
            for kind in ("topLevelPackages", "transitivePackages"):
                for p in framework.get(kind, []):
                    found[p["id"]] = p["resolvedVersion"]
    return found


def nuspec_info(package: str, version: str) -> tuple[str, str, str, Path]:
    folder = NUGET / package.lower() / version.lower()
    text = (folder / f"{package.lower()}.nuspec").read_text(encoding="utf-8-sig")

    def tag(pattern: str) -> str:
        m = re.search(pattern, text)
        return html.unescape(m.group(1).strip()) if m else ""

    license = LICENSE_OVERRIDES.get(package) or tag(r'<license type="expression">([^<]+)</license>') or "see package"
    return license, tag(r"<copyright>([^<]*)</copyright>"), tag(r"<projectUrl>([^<]+)</projectUrl>"), folder


def normalized(text: str) -> str:
    return text.replace("\r\n", "\n").strip() + "\n"


def main() -> int:
    pkgs = packages()
    lines: list[str] = []
    w = lines.append

    w("Invoklet — third-party notices")
    w("============================")
    w("")
    w("Invoklet is licensed under the GNU General Public License v3.0 (LICENSE.txt), except the")
    w("Invoklet.Runtime library, which is MIT-licensed (Invoklet.Runtime.LICENSE.txt). It includes and is")
    w("distributed with the third-party software listed below; each component remains under its own")
    w("license. Generated by scripts/make-third-party-notices.py — do not edit by hand.")
    w("")
    w("")
    w("1. Third-party source code included in Invoklet")
    w("---------------------------------------------")
    for name, where, lic, copyright_, url, license_file in SOURCE_COMPONENTS:
        w("")
        w(f"{name} — {lic}")
        w(f"  {copyright_}")
        w(f"  {url}")
        w(f"  In the Invoklet source: {where} (license: {license_file})")

    w("")
    w("")
    w("2. Packages distributed with the Invoklet application")
    w("---------------------------------------------------")
    notice_files: dict[str, tuple[str, list[str]]] = {}
    bsd_files: dict[str, str] = {}
    for package, version in sorted(pkgs.items(), key=lambda kv: kv[0].lower()):
        lic, copyright_, url, folder = nuspec_info(package, version)
        w("")
        w(f"{package} {version} — {lic}")
        if copyright_:
            w(f"  {copyright_}")
        if url:
            w(f"  {url}")
        for f in sorted(folder.iterdir()):
            upper = f.name.upper()
            if f.is_file() and "THIRD" in upper and upper.endswith((".TXT", ".MD")):
                body = normalized(f.read_text(encoding="utf-8-sig", errors="replace"))
                key = hashlib.sha1(body.encode()).hexdigest()
                notice_files.setdefault(key, (body, []))[1].append(package)
        if lic.startswith("BSD") and (folder / "LICENSE").exists():
            bsd_files[package] = normalized((folder / "LICENSE").read_text(encoding="utf-8-sig"))

    runtime = sorted(NUGET.glob("microsoft.netcore.app.runtime.*/10.*/THIRD-PARTY-NOTICES.TXT"))
    w("")
    w("")
    w("3. .NET runtime")
    w("---------------")
    w("")
    w("Self-contained Invoklet builds include the .NET runtime — MIT,")
    w("Copyright (c) .NET Foundation and Contributors, https://github.com/dotnet/runtime")
    if runtime:
        body = normalized(runtime[-1].read_text(encoding="utf-8-sig", errors="replace"))
        key = hashlib.sha1(body.encode()).hexdigest()
        notice_files.setdefault(key, (body, []))[1].append(".NET runtime " + runtime[-1].parent.name)

    w("")
    w("")
    w("4. License texts")
    w("----------------")
    w("")
    w("MIT License — applies to every component above marked MIT, with that component's copyright")
    w("notice in place of <copyright holders>:")
    w("")
    lines.extend(normalized((LICENSES / "MIT.txt").read_text(encoding="utf-8")).splitlines())
    w("")
    w("Apache License 2.0 — applies to every component above marked Apache-2.0:")
    w("")
    lines.extend(normalized((LICENSES / "Apache-2.0.txt").read_text(encoding="utf-8")).splitlines())
    w("")
    w("BSD-3-Clause — HTML Renderer:")
    w("")
    lines.extend(normalized((ROOT / SOURCE_COMPONENTS[1][5]).read_text(encoding="utf-8-sig")).splitlines())
    for package, body in sorted(bsd_files.items()):
        w("")
        w(f"BSD-3-Clause — {package}:")
        w("")
        lines.extend(body.splitlines())

    w("")
    w("")
    w("5. Notices shipped with components")
    w("----------------------------------")
    w("")
    w("Verbatim notice files that the packages above carry for third-party code embedded in them.")
    for body, owners in notice_files.values():
        w("")
        w("=" * 100)
        w("From: " + ", ".join(owners))
        w("=" * 100)
        w("")
        lines.extend(body.splitlines())

    OUTPUT.write_bytes(("\r\n".join(lines) + "\r\n").encode("utf-8"))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(pkgs)} packages, {len(notice_files)} notice files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
